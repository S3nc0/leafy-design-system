#!/usr/bin/env node
// Generates Leafy's Jetpack Compose and SwiftUI token files from tokens/tokens.json and tokens/zen-cues.json.
//
//   node tools/generate.mjs                          regenerate the Kotlin and Swift token files
//   node tools/generate.mjs --sounds <dir>           also copy the Zen sounds from <dir>
//                                                    (node_modules/uisfx/sounds/zen after `npm install uisfx`)
//
// Needs Node 18 or later and nothing else.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(fs.readFileSync(path.join(ROOT, 'tokens/tokens.json'), 'utf8'));
const zen = JSON.parse(fs.readFileSync(path.join(ROOT, 'tokens/zen-cues.json'), 'utf8'));
const KT = path.join(ROOT, 'android/leafy/src/main/kotlin/design/leafy');
const SW = path.join(ROOT, 'ios/LeafyDesign/Sources/LeafyDesign');
const HEADER = 'Generated by tools/generate.mjs from tokens/tokens.json. Change the tokens and run the generator again instead of editing this file.';

const camel = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const pascal = (s) => { const c = camel(s); return c[0].toUpperCase() + c.slice(1); };
const num = (v) => { const n = parseFloat(v); return Number.isInteger(n) ? String(n) : String(+n.toFixed(3)); };
const kdoc = (s, indent) => `${indent}/** ${s.replace(/\*\//g, '*​/')} */\n`;
const swdoc = (s, indent) => `${indent}/// ${s.replace(/\n/g, ' ')}\n`;
const write = (file, text) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); console.log('wrote', path.relative(ROOT, file)); };
// '#rrggbb' or '#rrggbbaa' -> [r, g, b, a] as 0-255.
const rgba = (v) => { const h = v.replace('#', ''); return [0, 2, 4, 6].map((i) => (i < h.length ? parseInt(h.slice(i, i + 2), 16) : 255)); };
const ktColor = (v) => { const [r, g, b, a] = rgba(v); return 'Color(0x' + [a, r, g, b].map((x) => x.toString(16).padStart(2, '0')).join('').toUpperCase() + ')'; };
const swColor = (v) => { const [r, g, b, a] = rgba(v); const hx = [r, g, b].map((x) => x.toString(16).padStart(2, '0')).join('').toUpperCase(); return a === 255 ? `Color(leafyHex: 0x${hx})` : `Color(leafyHex: 0x${hx}, opacity: ${num(a / 255)})`; };

/* ---------- Colours ---------- */

const themes = tokens.color.themes; // light, dark, light-hc, dark-hc
const themeName = (id) => pascal(id).replace(/Hc$/, 'HighContrast');
const roles = tokens.color.tokens.filter((c) => !c.name.startsWith('palette-'));
const valueIn = (c, theme) => (typeof c.value === 'string' ? c.value : c.value[theme]);
// Material 3 ColorScheme parameters (material3 1.3) that Leafy fills from its tokens.
const M3 = ['primary', 'on-primary', 'primary-container', 'on-primary-container', 'inverse-primary', 'secondary', 'on-secondary',
  'secondary-container', 'on-secondary-container', 'tertiary', 'on-tertiary', 'tertiary-container', 'on-tertiary-container', 'background',
  'on-background', 'surface', 'on-surface', 'surface-variant', 'on-surface-variant', 'surface-tint', 'inverse-surface', 'inverse-on-surface',
  'error', 'on-error', 'error-container', 'on-error-container', 'outline', 'outline-variant', 'scrim', 'surface-bright', 'surface-container',
  'surface-container-high', 'surface-container-highest', 'surface-container-low', 'surface-container-lowest', 'surface-dim'];
for (const r of M3) if (!roles.find((c) => c.name === r)) throw new Error('tokens.json is missing the Material role ' + r);

{
  let kt = `// ${HEADER}\npackage design.leafy.theme\n\nimport androidx.compose.material3.ColorScheme\nimport androidx.compose.material3.darkColorScheme\nimport androidx.compose.material3.lightColorScheme\nimport androidx.compose.runtime.Immutable\nimport androidx.compose.ui.graphics.Color\n\n`;
  kt += `/**\n * Every Leafy colour role for one theme: the Material 3 roles plus Leafy's status, layer, field, border,\n * focus, link and skeleton roles. Read it with \`Leafy.colors\` inside [LeafyTheme].\n */\n@Immutable\ndata class LeafyColors(\n`;
  for (const c of roles) kt += kdoc(c.usage || c.name, '    ') + `    val ${camel(c.name)}: Color,\n`;
  kt += `) {\n    /** The Material 3 colour scheme, so stock Material components use Leafy's roles. */\n    fun toColorScheme(dark: Boolean): ColorScheme = if (dark) darkColorScheme(\n`;
  const schemeArgs = M3.map((r) => `        ${camel(r)} = ${camel(r)},\n`).join('');
  kt += schemeArgs + `    ) else lightColorScheme(\n` + schemeArgs + `    )\n}\n`;
  for (const t of themes) {
    kt += `\n/** The ${t.name} theme. */\nval Leafy${themeName(t.id)}Colors = LeafyColors(\n`;
    for (const c of roles) kt += `    ${camel(c.name)} = ${ktColor(valueIn(c, t.id))},\n`;
    kt += `)\n`;
  }
  write(path.join(KT, 'theme/LeafyColors.kt'), kt);

  let sw = `// ${HEADER}\nimport SwiftUI\n\n/// Every Leafy colour role for one theme: the Material 3 roles plus Leafy's status, layer, field, border,\n/// focus, link and skeleton roles. Read it with \`@Environment(\\.leafyColors)\` under \`.leafyTheme()\`.\npublic struct LeafyColors: Equatable {\n`;
  for (const c of roles) sw += swdoc(c.usage || c.name, '    ') + `    public let ${camel(c.name)}: Color\n`;
  for (const t of themes) {
    const id = themeName(t.id);
    sw += `\n    /// The ${t.name} theme.\n    public static let ${id[0].toLowerCase() + id.slice(1)} = LeafyColors(\n`;
    sw += roles.map((c) => `        ${camel(c.name)}: ${swColor(valueIn(c, t.id))}`).join(',\n') + `\n    )\n`;
  }
  sw += `}\n`;
  write(path.join(SW, 'Generated/LeafyColors.generated.swift'), sw);
}

/* ---------- Typography ---------- */

const styles = tokens.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: s.family || g.family })));
const isM3Style = (n) => /^(display|headline|title|body|label)-(large|medium|small)$/.test(n);
// Dynamic Type style each Leafy style scales with on iOS.
const RELATIVE = { 'display-large': 'largeTitle', 'display-medium': 'largeTitle', 'display-small': 'largeTitle', 'headline-large': 'title',
  'headline-medium': 'title', 'headline-small': 'title2', 'title-large': 'title2', 'title-medium': 'headline', 'title-small': 'subheadline',
  'body-large': 'body', 'body-medium': 'callout', 'body-small': 'footnote', 'label-large': 'subheadline', 'label-medium': 'caption',
  'label-small': 'caption2', 'code-01': 'caption', 'code-02': 'callout' };
const SW_WEIGHT = { 100: 'ultraLight', 200: 'thin', 300: 'light', 400: 'regular', 500: 'medium', 600: 'semibold', 700: 'bold', 800: 'heavy', 900: 'black' };
{
  let kt = `// ${HEADER}\npackage design.leafy.theme\n\nimport androidx.compose.material3.Typography\nimport androidx.compose.runtime.Immutable\nimport androidx.compose.ui.text.TextStyle\nimport androidx.compose.ui.text.font.FontWeight\nimport androidx.compose.ui.unit.sp\n\n`;
  kt += `/** Leafy's type scale: the 15 Material 3 styles set in IBM Plex, plus the code styles. Read it with \`Leafy.typography\`. */\n@Immutable\ndata class LeafyTypography(\n`;
  for (const s of styles) kt += kdoc(s.usage, '    ') + `    val ${camel(s.name)}: TextStyle,\n`;
  kt += `) {\n    /** The Material 3 typography, so stock Material components use Leafy's scale. */\n    fun toMaterial(): Typography = Typography(\n`;
  for (const s of styles.filter((x) => isM3Style(x.name))) kt += `        ${camel(s.name)} = ${camel(s.name)},\n`;
  kt += `    )\n}\n\n/** Builds the type scale in [fonts]; the default is the bundled IBM Plex. */\nfun leafyTypography(fonts: LeafyFonts = LeafyFonts.Default) = LeafyTypography(\n`;
  for (const s of styles) {
    kt += `    ${camel(s.name)} = TextStyle(fontFamily = fonts.${s.family}, fontWeight = FontWeight(${s.fontWeight}), fontSize = ${num(s.fontSize)}.sp, lineHeight = ${num(s.lineHeight)}.sp, letterSpacing = ${num(s.letterSpacing)}.sp),\n`;
  }
  kt += `)\n`;
  write(path.join(KT, 'theme/LeafyTypography.kt'), kt);

  let sw = `// ${HEADER}\nimport SwiftUI\n\n/// Leafy's type scale: the 15 Material 3 styles set in IBM Plex, plus the code styles.\n/// Apply one with \`.leafyFont(.bodyMedium)\`; sizes scale with Dynamic Type.\npublic extension LeafyTextStyle {\n`;
  for (const s of styles) {
    if (!RELATIVE[s.name]) throw new Error('no Dynamic Type mapping for ' + s.name);
    sw += swdoc(s.usage, '    ') + `    static let ${camel(s.name)} = LeafyTextStyle(family: .${s.family}, size: ${num(s.fontSize)}, lineHeight: ${num(s.lineHeight)}, weight: .${SW_WEIGHT[s.fontWeight]}, tracking: ${num(s.letterSpacing)}, relativeTo: .${RELATIVE[s.name]})\n`;
  }
  sw += `}\n`;
  write(path.join(SW, 'Generated/LeafyTypography.generated.swift'), sw);
}

/* ---------- Spacing, sizes, radius, opacity, elevation, layout ---------- */

const family = (k) => tokens[k].tokens;
// Material 3 elevation levels in dp; tokens.json carries them as CSS shadows.
const ELEVATION_DP = [0, 1, 3, 6, 8, 12];
const parseShadow = (v) => (v === 'none' ? [] : v.split(/,(?![^(]*\))/).map((layer) => {
  const [x, y, blur, spread] = layer.trim().match(/-?[\d.]+px/g).map(parseFloat);
  const alpha = parseFloat(layer.match(/rgba\([^)]*,\s*([\d.]+)\)/)[1]);
  return { x, y, blur, spread, alpha };
}));
{
  const ktGroup = (name, note, items, fmt) => `/** ${note} */\nobject ${name} {\n` + items.map((t) => kdoc(t.usage, '    ') + `    val ${camel(t.name)} = ${fmt(t)}\n`).join('') + `}\n\n`;
  let kt = `// ${HEADER}\npackage design.leafy.theme\n\nimport androidx.compose.ui.unit.dp\n\n`;
  kt += ktGroup('LeafySpacing', tokens.spacing.note, family('spacing'), (t) => `${num(t.value)}.dp`);
  kt += ktGroup('LeafySize', tokens.size.note, family('size'), (t) => `${num(t.value)}.dp`);
  kt += ktGroup('LeafyRadius', tokens.radius.note + ' Full (9999) clamps to a pill.', family('radius'), (t) => `${num(t.value)}.dp`);
  kt += ktGroup('LeafyOpacity', tokens.opacity.note, family('opacity'), (t) => `${num(t.value)}f`);
  kt += `/** ${tokens.shadow.note || 'Elevation levels.'} Values are Material 3 elevation in dp; Leafy stays flat and uses them sparingly. */\nobject LeafyElevation {\n`;
  family('shadow').forEach((t, i) => { kt += kdoc(t.usage, '    ') + `    val ${camel(t.name)} = ${ELEVATION_DP[i] ?? 12}.dp\n`; });
  kt += `}\n\n`;
  kt += ktGroup('LeafyBreakpoints', tokens.breakpoint.note, family('breakpoint'), (t) => `${num(t.value)}.dp`);
  kt += ktGroup('LeafyGrid', tokens.grid.note, family('grid'), (t) => (/px$/.test(t.value) ? `${num(t.value)}.dp` : num(t.value)));
  write(path.join(KT, 'theme/LeafyTokens.kt'), kt.trimEnd() + '\n');

  const swGroup = (name, note, items, type, fmt) => `/// ${note}\npublic enum ${name} {\n` + items.map((t) => swdoc(t.usage, '    ') + `    public static let ${camel(t.name)}: ${type} = ${fmt(t)}\n`).join('') + `}\n\n`;
  let sw = `// ${HEADER}\nimport SwiftUI\n\n`;
  sw += swGroup('LeafySpacing', tokens.spacing.note, family('spacing'), 'CGFloat', (t) => num(t.value));
  sw += swGroup('LeafySize', tokens.size.note, family('size'), 'CGFloat', (t) => num(t.value));
  sw += swGroup('LeafyRadius', tokens.radius.note + ' Full (9999) clamps to a capsule.', family('radius'), 'CGFloat', (t) => num(t.value));
  sw += swGroup('LeafyOpacity', tokens.opacity.note, family('opacity'), 'Double', (t) => num(t.value));
  sw += `/// ${tokens.shadow.note || 'Elevation levels.'} Each level is the two-layer Material shadow (key and ambient).\npublic enum LeafyElevation {\n`;
  family('shadow').forEach((t) => {
    const layers = parseShadow(t.value).map((l) => `LeafyShadowLayer(opacity: ${num(l.alpha)}, radius: ${num(l.blur / 2)}, x: ${num(l.x)}, y: ${num(l.y)})`);
    sw += swdoc(t.usage, '    ') + `    public static let ${camel(t.name)}: [LeafyShadowLayer] = [${layers.join(', ')}]\n`;
  });
  sw += `}\n\n`;
  sw += swGroup('LeafyBreakpoints', tokens.breakpoint.note, family('breakpoint'), 'CGFloat', (t) => num(t.value));
  sw += swGroup('LeafyGrid', tokens.grid.note, family('grid'), 'CGFloat', (t) => num(t.value));
  write(path.join(SW, 'Generated/LeafyTokens.generated.swift'), sw.trimEnd() + '\n');
}

/* ---------- Sound ---------- */

{
  const sound = family('sound');
  const setting = (n) => sound.find((t) => t.name === n).value;
  const events = sound.filter((t) => !['sound-pack', 'sound-volume', 'sound-max-voices'].includes(t.name))
    .map((t) => ({ name: t.name.replace(/^sound-/, ''), cue: t.value, usage: t.usage }));
  const cueNames = new Set(zen.cues.map((c) => c.name));
  for (const e of events) if (e.cue !== 'none' && !cueNames.has(e.cue)) throw new Error(`sound-${e.name} maps to unknown cue ${e.cue}`);
  const res = (c) => 'zen_' + c.replace(/-/g, '_');

  let kt = `// ${HEADER}\npackage design.leafy.sound\n\nimport design.leafy.R\n\n/** The ${zen.cues.length} uisfx cues, played in the Zen pack. Loops repeat until you stop the handle [LeafySound.play] returns. */\nenum class LeafyCue(val id: String, val loop: Boolean) {\n`;
  kt += zen.cues.map((c) => kdoc(`${c.label}: ${c.description}`, '    ') + `    ${pascal(c.name)}("${c.name}", ${c.loop}),\n`).join('') + `    ;\n\n    /** The Zen sound file in res/raw. */\n    val rawRes: Int\n        get() = when (this) {\n`;
  kt += zen.cues.map((c) => `            ${pascal(c.name)} -> R.raw.${res(c.name)}\n`).join('') + `        }\n}\n\n`;
  kt += `/** Component events and the cue each plays (tokens \`sound-<event>\`). A null cue is silent by design. */\nenum class LeafySoundEvent(val cue: LeafyCue?) {\n`;
  kt += events.map((e) => kdoc(e.usage, '    ') + `    ${pascal(e.name)}(${e.cue === 'none' ? 'null' : 'LeafyCue.' + pascal(e.cue)}),\n`).join('') + `}\n\n`;
  kt += `/** Starting values from the sound tokens. */\nobject LeafySoundDefaults {\n    /** sound-pack */\n    const val PACK = "${setting('sound-pack')}"\n    /** sound-volume: the master volume for people who have never changed it. */\n    const val VOLUME = ${num(setting('sound-volume'))}f\n    /** sound-max-voices: sounds playing at once; a new one replaces the oldest. */\n    const val MAX_VOICES = ${num(setting('sound-max-voices'))}\n}\n`;
  write(path.join(KT, 'sound/LeafySoundCues.kt'), kt);

  let sw = `// ${HEADER}\nimport Foundation\n\n/// The ${zen.cues.length} uisfx cues, played in the Zen pack. Loops repeat until you stop the handle \`LeafySound.play\` returns.\npublic enum LeafyCue: String, CaseIterable, Sendable {\n`;
  sw += zen.cues.map((c) => swdoc(`${c.label}: ${c.description}`, '    ') + `    case \`${camel(c.name)}\` = "${c.name}"\n`).join('');
  sw += `\n    /// True for the six state loops (loading, processing, recording, connecting, scanning, streaming).\n    public var isLoop: Bool {\n        switch self {\n        case ${zen.cues.filter((c) => c.loop).map((c) => '.`' + camel(c.name) + '`').join(', ')}: return true\n        default: return false\n        }\n    }\n\n    /// The Zen sound file name inside the package's Sounds folder.\n    public var fileName: String { "zen-\\(rawValue)" }\n}\n\n`;
  sw += `/// Component events and the cue each plays (tokens \`sound-<event>\`). A nil cue is silent by design.\npublic enum LeafySoundEvent: String, CaseIterable, Sendable {\n`;
  sw += events.map((e) => swdoc(e.usage, '    ') + `    case \`${camel(e.name)}\` = "${e.name}"\n`).join('');
  sw += `\n    public var cue: LeafyCue? {\n        switch self {\n` + events.map((e) => `        case .\`${camel(e.name)}\`: return ${e.cue === 'none' ? 'nil' : '.`' + camel(e.cue) + '`'}\n`).join('') + `        }\n    }\n}\n\n`;
  sw += `/// Starting values from the sound tokens.\npublic enum LeafySoundDefaults {\n    /// sound-pack\n    public static let pack = "${setting('sound-pack')}"\n    /// sound-volume: the master volume for people who have never changed it.\n    public static let volume: Float = ${num(setting('sound-volume'))}\n    /// sound-max-voices: sounds playing at once; a new one replaces the oldest.\n    public static let maxVoices = ${num(setting('sound-max-voices'))}\n}\n`;
  write(path.join(SW, 'Generated/LeafySound.generated.swift'), sw);

  // Optional: copy the Zen sound files from the uisfx package.
  const i = process.argv.indexOf('--sounds');
  if (i > 0) {
    const dir = path.resolve(process.argv[i + 1] || '');
    const raw = path.join(ROOT, 'android/leafy/src/main/res/raw');
    const ios = path.join(SW, 'Resources/Sounds');
    fs.mkdirSync(raw, { recursive: true });
    fs.mkdirSync(ios, { recursive: true });
    for (const c of zen.cues) {
      fs.copyFileSync(path.join(dir, c.name + '.ogg'), path.join(raw, res(c.name) + '.ogg'));
      fs.copyFileSync(path.join(dir, c.name + '.mp3'), path.join(ios, 'zen-' + c.name + '.mp3'));
    }
    console.log(`copied ${zen.cues.length} Zen sounds as .ogg (Android) and .mp3 (iOS)`);
  }
}
